"""Writes src/dev/local/ebstrip/HelpText.java from ../channel-strip/help/help_text.py (run by build.sh)."""
import importlib.util
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("help_text", HERE.parent / "channel-strip" / "help" / "help_text.py")
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)
entries = {}
for key, text in mod.HELP.items():
    entries[key if key.endswith((".desc", ".title")) else key + ".desc"] = text
lines = [
    "package dev.local.ebstrip;",
    "",
    "import java.util.HashMap;",
    "import java.util.Map;",
    "",
    "/** F1 device help for the EB devices. Generated by eb-strip-console/gen_help.py from channel-strip/help/help_text.py; do not edit. */",
    "final class HelpText {",
    "    private static final Map<String, String> TEXT = new HashMap<>();",
    "    static {",
]
for key in sorted(entries):
    lines.append(f"        TEXT.put({json.dumps(key)}, {json.dumps(entries[key], ensure_ascii=False)});")
lines += [
    "    }",
    "",
    "    /** The text for a help key, or null when it isn't one of ours. */",
    "    static String get(String key) {",
    "        return key == null ? null : TEXT.get(key);",
    "    }",
    "}",
    "",
]
(HERE / "src" / "dev" / "local" / "ebstrip" / "HelpText.java").write_text("\n".join(lines), encoding="utf-8")
print(f"HelpText.java: {len(entries)} entries")
